#!/usr/bin/env bash
# strip_to_docker_baseline.sh — reduce an iptables-save capture to a docker-only baseline.
#
# Usage: strip_to_docker_baseline.sh [--dry-run] [--restore-bin BIN] <capture-file>
#
# Reads an iptables-save / ip6tables-save capture and emits on stdout the
# baseline that Docker alone would produce on this host:
#
#   *filter
#     :INPUT ACCEPT             (policy forced ACCEPT — viswall enforces the host filter)
#     -A INPUT -i docker0 -j ACCEPT          (docker bridge -> host allowance)
#     -A INPUT -i br-*    -j ACCEPT          (same for docker user bridges)
#     FORWARD: only the jumps to docker chains (DOCKER-USER/DOCKER-FORWARD/DOCKER)
#              plus docker's docker0/br-* FORWARD rules
#     every chain reachable from FORWARD among the DOCKER* chains, with their
#     rules — EXCEPT operator rules appended to DOCKER-USER (the ctorigdstport
#     internal-port drops; viswall now enforces those — recorded decision)
#   *nat      (verbatim — DOCKER DNAT/MASQUERADE are docker-owned)
#   every other table (raw, mangle, ...) is emitted with its builtin chains
#     emptied: operator anti-spoof raw rules are removed, not left behind.
#
# iptables-restore replaces only the tables present in its input, so emitting
# an emptied *raw table is REQUIRED to actually remove operator raw rules.
#
# Non-dry runs validate the emitted baseline with `BIN --test` (default
# iptables-restore; pass --restore-bin ip6tables-restore for a v6 capture) and
# exit with its status. --dry-run prints the validation command without
# executing it; the baseline still goes to stdout in both modes.
set -euo pipefail

RESTORE_BIN="iptables-restore"
DRY_RUN=0

usage() {
    cat >&2 <<EOF
usage: $0 [--dry-run] [--restore-bin BIN] <capture-file>

  --dry-run           print the validation command instead of executing it
  --restore-bin BIN   validation binary (default: iptables-restore; use
                      ip6tables-restore when the capture is an ip6tables-save)
EOF
    exit 2
}

while [ "$#" -gt 0 ]; do
    case "$1" in
        --dry-run) DRY_RUN=1; shift ;;
        --restore-bin) RESTORE_BIN="${2:?--restore-bin requires an argument}"; shift 2 ;;
        -h|--help) usage ;;
        -*) echo "error: unknown option: $1" >&2; usage ;;
        *) break ;;
    esac
done

CAPTURE="${1:-}"
if [ -z "$CAPTURE" ]; then
    echo "error: missing <capture-file> argument" >&2
    usage
fi
if [ ! -f "$CAPTURE" ]; then
    echo "error: capture file not found: $CAPTURE" >&2
    exit 2
fi
if ! command -v "$RESTORE_BIN" >/dev/null 2>&1; then
    echo "error: validation binary not found: $RESTORE_BIN" >&2
    exit 2
fi

BASELINE="$(awk -v src="$CAPTURE" -v stamp="$(date -u '+%Y-%m-%dT%H:%M:%SZ')" '
# --- parse ---------------------------------------------------------------
$0 ~ /^#/ { next }
$0 ~ /^\*/ {
    table = substr($0, 2)
    if (!(table in seen)) { seen[table] = 1; torder[++tnum] = table }
    next
}
$0 ~ /^:/ {
    name = $1
    sub(/^:/, "", name)
    decl[table, name] = $0
    isdecl[table, name] = 1
    dorder[table, ++dcount[table]] = name
    next
}
$0 ~ /^-A / {
    chain = $2
    rest = $0
    # keep a leading space so every token can be matched as " -x "
    sub(/^-A [^ ]+ /, " ", rest)
    rule[table, chain, ++rcount[table, chain]] = rest
    next
}
{ next }

# --- emit ----------------------------------------------------------------
END {
    print "# Docker-only baseline generated by scripts/strip_to_docker_baseline.sh"
    print "#   source: " src
    print "#   date:   " stamp
    print "# DOCKER-USER internal-port drops were removed (viswall enforces them now)."

    # Chains reachable from FORWARD via -j, restricted to docker-owned names.
    reached["FORWARD"] = 1
    changed = 1
    while (changed) {
        changed = 0
        for (c in reached) {
            for (i = 1; i <= rcount["filter", c]; i++) {
                r = rule["filter", c, i]
                if (match(r, / -j /)) {
                    tgt = substr(r, RSTART + 4)
                    sub(/ .*/, "", tgt)
                    if (!(tgt in reached) && isdecl["filter", tgt] && tgt ~ /^DOCKER/) {
                        reached[tgt] = 1
                        changed = 1
                    }
                }
            }
        }
    }

    for (t = 1; t <= tnum; t++) {
        tab = torder[t]
        if (tab == "nat") {
            print "*nat"
            for (i = 1; i <= dcount["nat"]; i++) { n = dorder["nat", i]; print decl["nat", n] }
            for (i = 1; i <= dcount["nat"]; i++) {
                n = dorder["nat", i]
                for (j = 1; j <= rcount["nat", n]; j++) print "-A " n rule["nat", n, j]
            }
            print "COMMIT"
            continue
        }
        if (tab != "filter") {
            # operator table (raw, mangle, ...): keep builtin chains, empty them.
            print "*" tab
            for (i = 1; i <= dcount[tab]; i++) {
                n = dorder[tab, i]
                if (decl[tab, n] !~ /^:[^ ]+ - \[/) print decl[tab, n]
            }
            print "COMMIT"
            continue
        }

        print "*filter"
        for (i = 1; i <= dcount["filter"]; i++) {
            n = dorder["filter", i]
            if (n == "INPUT") { print ":INPUT ACCEPT [0:0]" }
            else if (n == "FORWARD" || n == "OUTPUT") { print decl["filter", n] }
            else if (n in reached) { print decl["filter", n] }
        }
        for (i = 1; i <= dcount["filter"]; i++) {
            n = dorder["filter", i]
            if (n == "INPUT") {
                for (j = 1; j <= rcount["filter", n]; j++) {
                    r = rule["filter", n, j]
                    if (r ~ / -i (docker0|br-[0-9a-f]+)/ && r ~ / -j ACCEPT$/) print "-A INPUT" r
                }
            } else if (n == "FORWARD") {
                for (j = 1; j <= rcount["filter", n]; j++) {
                    r = rule["filter", n, j]
                    keep = (r ~ / -i (docker0|br-[0-9a-f]+)/) || (r ~ / -o (docker0|br-[0-9a-f]+)/)
                    if (!keep && match(r, / -j /)) {
                        tgt = substr(r, RSTART + 4)
                        sub(/ .*/, "", tgt)
                        if (tgt in reached) keep = 1
                    }
                    if (keep) print "-A " n r
                }
            } else if (n in reached) {
                for (j = 1; j <= rcount["filter", n]; j++) {
                    r = rule["filter", n, j]
                    # operator-appended internal-port protection — viswall owns it now.
                    if (n == "DOCKER-USER" && r ~ /ctorigdstport/) continue
                    print "-A " n r
                }
            }
        }
        print "COMMIT"
    }
}
' "$CAPTURE")" || { echo "error: stripping failed" >&2; exit 2; }

if [ -z "$BASELINE" ]; then
    echo "error: no tables found in capture: $CAPTURE" >&2
    exit 2
fi

printf '%s\n' "$BASELINE"

if [ "$DRY_RUN" -eq 1 ]; then
    echo "[DRY-RUN] would run: $RESTORE_BIN --test < (baseline generated from $CAPTURE)" >&2
    exit 0
fi

if ! printf '%s\n' "$BASELINE" | "$RESTORE_BIN" --test; then
    echo "error: $RESTORE_BIN --test rejected the generated baseline (capture: $CAPTURE)" >&2
    exit 1
fi
